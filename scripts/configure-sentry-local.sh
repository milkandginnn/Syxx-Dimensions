#!/usr/bin/env bash
# configure-sentry-local.sh — After Sentry is deployed, run this locally to
# configure environment variables and verify connectivity.
#
# Usage:
#   1. SSH to your server and collect the 4 DSNs from the deployment output
#   2. Run this script with the DSNs as arguments:
#      bash scripts/configure-sentry-local.sh \
#        --macos-dsn https://key@host/1 \
#        --windows-dsn https://key@host/2 \
#        --linux-dsn https://key@host/3 \
#        --server-dsn https://key@host/4

set -euo pipefail

MACOS_DSN=""
WINDOWS_DSN=""
LINUX_DSN=""
SERVER_DSN=""
SENTRY_URL=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --macos-dsn) MACOS_DSN="$2"; shift 2 ;;
        --windows-dsn) WINDOWS_DSN="$2"; shift 2 ;;
        --linux-dsn) LINUX_DSN="$2"; shift 2 ;;
        --server-dsn) SERVER_DSN="$2"; shift 2 ;;
        --sentry-url) SENTRY_URL="$2"; shift 2 ;;
        *) echo "Unknown option: $1"; exit 1 ;;
    esac
done

if [ -z "$MACOS_DSN" ] || [ -z "$SERVER_DSN" ]; then
    echo "Usage: bash configure-sentry-local.sh \\"
    echo "  --macos-dsn <DSN> \\"
    echo "  --windows-dsn <DSN> \\"
    echo "  --linux-dsn <DSN> \\"
    echo "  --server-dsn <DSN> \\"
    echo "  [--sentry-url https://sentry.syxx.app]"
    echo ""
    echo "Collect DSNs from your Sentry server:"
    echo "  Settings → Projects → [project] → Client Keys (DSN)"
    exit 1
fi

echo "=== Configuring Sentry DSNs locally ==="

# --- macOS: write to UserDefaults ---
echo "Setting macOS SENTRY_DSN in UserDefaults..."
defaults write com.milkandgin.syxx sentry_dsn "$MACOS_DSN"
echo "  ✅ macOS DSN configured (UserDefaults)"

# --- Server: write to .env file ---
ENV_FILE="/Users/masterrabbit/Software/Syxx/Server/.env"
echo ""
echo "Writing server SENTRY_DSN to $ENV_FILE..."
cat > "$ENV_FILE" << EOF
# Sentry crash/error reporting — generated by configure-sentry-local.sh
# DO NOT commit this file (it's in .gitignore)
SENTRY_DSN=${SERVER_DSN}
SYXX_ENVIRONMENT=development
EOF
echo "  ✅ Server .env written"

# --- Shell environment: export for CLI tools ---
SHELL_RC="$HOME/.zshrc"
echo ""
echo "Adding SENTRY_DSN to $SHELL_RC (for macOS CLI tools)..."

# Remove old entry if present
sed -i '' '/# Syxx Sentry DSN/d' "$SHELL_RC" 2>/dev/null || true
sed -i '' '/export SENTRY_DSN=/d' "$SHELL_RC" 2>/dev/null || true

cat >> "$SHELL_RC" << EOF

# Syxx Sentry DSN (macOS CLI) — generated by configure-sentry-local.sh
export SENTRY_DSN="${MACOS_DSN}"
EOF
echo "  ✅ SENTRY_DSN added to $SHELL_RC"

# --- Windows: write to .env file for local dev ---
WIN_ENV_FILE="/Users/masterrabbit/Software/Syxx/Windows/.env"
echo ""
echo "Writing Windows SENTRY_DSN to $WIN_ENV_FILE..."
cat > "$WIN_ENV_FILE" << EOF
# Sentry crash/error reporting — generated by configure-sentry-local.sh
# DO NOT commit this file (it's in .gitignore)
SENTRY_DSN=${WINDOWS_DSN}
SYXX_ENVIRONMENT=development
EOF
echo "  ✅ Windows .env written"
echo "  ℹ️  For Visual Studio, add to launchSettings.json or set as system env var:"
echo "     [System.Environment]::SetEnvironmentVariable('SENTRY_DSN', '${WINDOWS_DSN}', 'User')"

# --- Linux: write to .env file for local dev ---
LINUX_ENV_FILE="/Users/masterrabbit/Software/Syxx/Linux/Ubuntu/.env"
echo ""
echo "Writing Linux SENTRY_DSN to $LINUX_ENV_FILE..."
cat > "$LINUX_ENV_FILE" << EOF
# Sentry crash/error reporting — generated by configure-sentry-local.sh
# DO NOT commit this file (it's in .gitignore)
SENTRY_DSN=${LINUX_DSN}
SYXX_ENVIRONMENT=development
EOF
echo "  ✅ Linux .env written"
echo "  ℹ️  On the Linux target, add to ~/.bashrc or /etc/environment:"
echo "     export SENTRY_DSN='${LINUX_DSN}'"

# --- Verify connectivity ---
echo ""
echo "=== Verifying Sentry connectivity ==="
if [ -n "$SENTRY_URL" ]; then
    if curl -sf "${SENTRY_URL}/_health/" >/dev/null 2>&1; then
        echo "  ✅ Sentry is reachable at ${SENTRY_URL}"
    else
        echo "  ⚠️  Cannot reach Sentry at ${SENTRY_URL}"
        echo "  Check that the server is running and accessible."
    fi
else
    echo "  (skipped — pass --sentry-url to verify)"
fi

echo ""
echo "=== Summary ==="
echo "macOS DSN:   ${MACOS_DSN:0:30}... → UserDefaults + ~/.zshrc"
echo "Windows DSN: ${WINDOWS_DSN:0:30}... → Windows/.env"
echo "Linux DSN:   ${LINUX_DSN:0:30}... → Linux/Ubuntu/.env"
echo "Server DSN:  ${SERVER_DSN:0:30}... → Server/.env"
echo ""
echo "=== Next steps ==="
echo "1. Restart any running Syxx GUI/CLI to pick up the new DSN"
echo "2. On Windows dev machine, set as user environment variable:"
echo "   [System.Environment]::SetEnvironmentVariable('SENTRY_DSN', '${WINDOWS_DSN}', 'User')"
echo "3. On Linux target, add to ~/.bashrc:"
echo "   export SENTRY_DSN='${LINUX_DSN}'"
echo "4. For CI, add SENTRY_AUTH_TOKEN and SENTRY_ORG as GitHub secrets:"
echo "   gh secret set SENTRY_AUTH_TOKEN --body '<your-token>'"
echo "   gh secret set SENTRY_ORG --body '<your-org-slug>'"
echo "5. Build and run Syxx — crash reports will flow to Sentry"
